import com.fasterxml.jackson.databind.ObjectMapper;
import com.sieglings.chronicles.ChroniclesContent;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Writes static/js/dominion-data.js from ChroniclesContent so the Dominion prototype runs on
 * Chronicles' real professions, gathering spots, recipes, items and routes instead of a copy.
 *
 *   ./mvnw -q -DskipTests compile
 *   ./mvnw -q dependency:build-classpath -Dmdep.outputFile=cp.txt
 *   javac -cp "target/classes:$(cat cp.txt)" -d /tmp/dx tools/dominion/ExportChroniclesContent.java
 *   java -cp "target/classes:$(cat cp.txt):/tmp/dx" ExportChroniclesContent src/main/resources/static/js/dominion-data.js
 */
public class ExportChroniclesContent {
    public static void main(String[] args) throws Exception {
        Map<String, Object> out = new LinkedHashMap<>();
        out.put("skills", ChroniclesContent.SKILLS);
        out.put("activities", ChroniclesContent.ACTIVITIES);
        out.put("recipes", ChroniclesContent.RECIPES);
        out.put("items", ChroniclesContent.ITEMS);
        out.put("weapons", ChroniclesContent.WEAPONS);
        out.put("gearBonuses", ChroniclesContent.GEAR_BONUSES);
        out.put("hazardWards", ChroniclesContent.HAZARD_WARD_ITEMS);
        out.put("routes", ChroniclesContent.ROUTES);
        out.put("buildings", ChroniclesContent.BUILDINGS);
        out.put("bondMilestones", ChroniclesContent.BOND_MILESTONE_NAMES);
        out.put("affinityMilestones", ChroniclesContent.AFFINITY_MILESTONE_NAMES);
        String json = new ObjectMapper().writeValueAsString(out);
        Files.writeString(Path.of(args[0]),
                "/* Generated by tools/dominion/ExportChroniclesContent.java from ChroniclesContent. Do not edit by hand. */\n"
                        + "window.DOMINION_CHRONICLES = " + json + ";\n");
    }
}
