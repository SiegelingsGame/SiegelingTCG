import com.fasterxml.jackson.databind.ObjectMapper;
import com.sieglings.chronicles.ChroniclesContent;
import com.sieglings.service.CreatureRegistry;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Writes the Dominion data files from the game's own content so Dominion runs on the real
 * Chronicles professions, recipes, items, routes and realm tables, the creature registry,
 * and the Keep's event and Voices catalogs instead of hand copies.
 *
 *   ./mvnw -q -DskipTests compile
 *   ./mvnw -q dependency:build-classpath -Dmdep.outputFile=cp.txt
 *   javac -cp "target/classes:$(cat cp.txt)" -d /tmp/dx tools/dominion/ExportDominionContent.java
 *   java -cp "target/classes:$(cat cp.txt):/tmp/dx" ExportDominionContent src/main/resources/static/js
 */
public class ExportDominionContent {
    public static void main(String[] args) throws Exception {
        ObjectMapper json = new ObjectMapper();
        Map<String, Object> out = new LinkedHashMap<>();
        out.put("skills", ChroniclesContent.SKILLS);
        out.put("activities", ChroniclesContent.ACTIVITIES);
        out.put("recipes", ChroniclesContent.RECIPES);
        out.put("items", ChroniclesContent.ITEMS);
        out.put("weapons", ChroniclesContent.WEAPONS);
        out.put("gearBonuses", ChroniclesContent.GEAR_BONUSES);
        out.put("hazardWards", ChroniclesContent.HAZARD_WARD_ITEMS);
        out.put("routes", ChroniclesContent.ROUTES);
        out.put("twists", ChroniclesContent.TWISTS);
        out.put("buildings", ChroniclesContent.BUILDINGS);
        out.put("buildingRank", ChroniclesContent.BUILDING_RANK);
        out.put("bondMilestones", ChroniclesContent.BOND_MILESTONE_NAMES);
        out.put("affinityMilestones", ChroniclesContent.AFFINITY_MILESTONE_NAMES);
        out.put("threats", ChroniclesContent.THREATS);
        out.put("fronts", ChroniclesContent.FRONTS);
        out.put("donationPoints", ChroniclesContent.DONATION_POINTS);
        out.put("defenseThresholds", ChroniclesContent.DEFENSE_THRESHOLDS);
        out.put("tradeable", ChroniclesContent.TRADEABLE);
        out.put("realm", Map.of("marketFee", ChroniclesContent.MARKET_FEE, "marketMaxListings", ChroniclesContent.MARKET_MAX_LISTINGS,
                "guildRank", ChroniclesContent.GUILD_RANK, "guildMaxMembers", ChroniclesContent.GUILD_MAX_MEMBERS,
                "crownsPerLevel", ChroniclesContent.CROWNS_PER_LEVEL, "rosterCap", ChroniclesContent.ROSTER_CAP,
                "maxPendingTamings", ChroniclesContent.MAX_PENDING_TAMINGS, "tamingExpiryMs", ChroniclesContent.TAMING_EXPIRY_MS));
        List<Map<String, Object>> creatures = new ArrayList<>();
        for (CreatureRegistry.Creature c : CreatureRegistry.all()) {
            Map<String, Object> row = new LinkedHashMap<>();
            row.put("id", c.id());
            row.put("name", c.name());
            row.put("element", c.element().name());
            row.put("rarity", c.rarity().name());
            row.put("cls", ChroniclesContent.CLASS_OVERRIDES.getOrDefault(c.id(), c.creatureClass()));
            row.put("from", c.evolvesFromId());
            row.put("to", c.evolvesToId());
            row.put("stage", c.stage());
            creatures.add(row);
        }
        out.put("creatures", creatures);
        Path dir = Path.of(args[0]);
        Files.writeString(dir.resolve("dominion-data.js"),
                "/* Generated by tools/dominion/ExportDominionContent.java from ChroniclesContent and CreatureRegistry. Do not edit by hand. */\n"
                        + "window.DOMINION_CHRONICLES = " + json.writeValueAsString(out) + ";\n");
        Map<String, Object> keep = new LinkedHashMap<>();
        keep.put("events", json.readTree(Path.of("src/main/resources/keep/keep-events.json").toFile()).get("events"));
        keep.put("lore", json.readTree(Path.of("src/main/resources/keep/keep-lore.json").toFile()));
        // Enclave residents' rapport ladders: two element rungs plus a personal bond rung.
        Map<String, Object> tasks = new LinkedHashMap<>();
        tasks.put("elements", com.sieglings.keep.KeepEnclaveTaskCatalog.shippedElementTasks());
        tasks.put("bond", com.sieglings.keep.KeepEnclaveTaskCatalog.shippedBondTasks());
        keep.put("enclaveTasks", tasks);
        Files.writeString(dir.resolve("dominion-keep-data.js"),
                "/* Generated by tools/dominion/ExportDominionContent.java from resources/keep/*.json. Do not edit by hand. */\n"
                        + "window.DOMINION_KEEP = " + json.writeValueAsString(keep) + ";\n");
    }
}
